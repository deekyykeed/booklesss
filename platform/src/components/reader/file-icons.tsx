export type FileKind = "pdf" | "image" | "sheet" | "doc";

const IMAGE_EXT = ["png", "jpg", "jpeg", "gif", "webp", "avif", "bmp", "svg", "heic", "heif"];
const SHEET_EXT = ["xls", "xlsx", "csv", "tsv", "numbers", "ods"];

/** Maps a filename to the badge it gets. Anything unrecognised reads as a
 *  generic document rather than falling back to nothing. */
export function fileKind(name: string): FileKind {
  const dot = name.lastIndexOf(".");
  const ext = dot === -1 ? "" : name.slice(dot + 1).toLowerCase();
  if (ext === "pdf") return "pdf";
  if (IMAGE_EXT.includes(ext)) return "image";
  if (SHEET_EXT.includes(ext)) return "sheet";
  return "doc";
}

