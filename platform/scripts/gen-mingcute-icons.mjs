// Regenerates src/components/icons/mingcute.tsx from @iconify-json/mingcute.
//   npm run gen:mingcute
//
// Same shape and the same reason as gen-icons.mjs: the Mingcute set is ~3,340
// icons, and the sidebar that draws this one is a client component, so
// importing the set would ship the lot to the browser. Only the names in ICONS
// are resolved, at author time, and only their path bodies land in the
// generated module.
//
// Mingcute is deliberately a second, narrow set — MynaUI is still the app's
// icon system (see .claude/CLAUDE.md). Reach for this one only where the owner
// has picked a Mingcute glyph specifically.
import { getIconData, iconToSVG } from "@iconify/utils";
import mingcute from "@iconify-json/mingcute/icons.json" with { type: "json" };
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

/* Every Mingcute icon the UI draws, grouped by where it's used so an unused one
 * is obvious. */
const ICONS = [
  // the reader sidebar's lesson caret — rotated -90° to point right when the
  // unit is collapsed, which is exactly Mingcute's "Right Small Line".
  "down-small-line",
];

const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "components", "icons", "mingcute.tsx");

const NAMES = [...new Set(ICONS)];

const bodies = {};
for (const name of NAMES) {
  const data = getIconData(mingcute, name);
  if (!data) throw new Error(`Unknown Mingcute icon: "${name}"`);
  // 24-grid, stroke-based like MynaUI — the body keeps stroke="currentColor",
  // so colour and stroke width stay the caller's to set. Mingcute's own
  // stroke-width is 2 (MynaUI's is 1.5), so a glyph drawn at the same size
  // reads heavier unless strokeWidth is passed.
  bodies[name] = iconToSVG(data, { height: 24, width: 24 }).body;
}

const union = NAMES.map((n) => `  | "${n}"`).join("\n");
const entries = NAMES.map((n) => `  "${n}":\n    '${bodies[n].replace(/'/g, "\\'")}',`).join("\n");

writeFileSync(
  OUT,
  `/* AUTO-GENERATED by scripts/gen-mingcute-icons.mjs — do not edit by hand.
 *
 * Mingcute Icons, resolved from the local @iconify-json/mingcute package at
 * generation time. Add a name to ICONS in the script and rerun
 * \`npm run gen:mingcute\`.
 *
 * A second set alongside MynaUI, kept deliberately small — see the script.
 */

import type { CSSProperties } from "react";

export type MingcuteIconName =
${union};

/* Path bodies only — a 24-grid viewBox is added by the component. Each keeps
 * stroke="currentColor", so an icon takes the colour of the text around it. */
const BODIES: Record<MingcuteIconName, string> = {
${entries}
};

/**
 * One icon, inlined as SVG. Safe in server and client components alike: no set
 * is imported at runtime, only the bodies above.
 *
 * \`strokeWidth\` overrides Mingcute's 2 — which is a third heavier than
 * MynaUI's 1.5, so an icon sat beside MynaUI glyphs usually wants it nudged
 * down to match.
 */
export function MingcuteIcon({
  name,
  size = 20,
  className,
  style,
  strokeWidth,
}: {
  name: MingcuteIconName;
  size?: number;
  className?: string;
  style?: CSSProperties;
  strokeWidth?: number;
}) {
  const body = strokeWidth
    ? BODIES[name].replace(/stroke-width="[^"]*"/g, \`stroke-width="\${strokeWidth}"\`)
    : BODIES[name];

  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      width={size}
      height={size}
      className={className}
      style={style}
      aria-hidden="true"
      focusable="false"
      dangerouslySetInnerHTML={{ __html: body }}
    />
  );
}
`,
  "utf8",
);

console.log(`Wrote ${NAMES.length} icons to ${OUT}`);
