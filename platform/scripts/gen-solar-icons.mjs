// Regenerates src/components/icons/solar.tsx from @iconify-json/solar.
//   npm run gen:solar
//
// Same trick as gen-icons.mjs: the Solar set is ~7,400 icons, so importing it
// into a client component would ship the lot to the browser. The names listed
// below are resolved here, at author time, and only their path bodies land in
// the generated module.
//
// Two Solar styles are drawn here. "-linear" (stroke, 1.5, currentColor) is the
// /workspace rail's, with "-bold" as its filled twin where a mark has to read as
// ON (the favourited star). "-bold-duotone" is the dashboard stat cards': one
// filled shape plus a second at opacity .5, both currentColor — so a duotone
// mark takes the tile's hue and shades itself.
import { getIconData, iconToSVG } from "@iconify/utils";
import solar from "@iconify-json/solar/icons.json" with { type: "json" };
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ICONS = [
  // workspace rail — the narrow icon column
  "widget-linear",
  "file-text-linear",
  "calendar-linear",
  "share-linear",
  "clock-circle-linear",
  "chat-round-dots-linear",
  "microphone-3-linear",
  "settings-linear",
  "headphones-round-linear",
  "logout-2-linear",
  // workspace panel — search, collapse, section chevrons, favourite stars
  "magnifer-linear",
  "double-alt-arrow-left-linear",
  "alt-arrow-down-linear",
  "star-linear",
  "star-bold",
  // dashboard stat cards — duotone, one per stat, drawn in the stat's own hue
  "chart-2-bold-duotone", // Performance — bars stepping up
  "bolt-bold-duotone", // Streak — the zap it replaces
  "notebook-minimalistic-bold-duotone", // Coverage — an open book
  "clock-circle-bold-duotone", // Time this week
  /* Callout kinds — the mark at the top-left of an in-text container, and now
     the ONLY thing there: the owner dropped the word beside it (2026-08-02), so
     each of these has to carry its kind alone. See CALLOUTS in
     reader/LessonView.tsx. */
  "key-bold-duotone", // Key point
  "danger-triangle-bold-duotone", // Watch out
  "clipboard-text-bold-duotone", // Example
  "target-bold-duotone", // In the exam
  /* The checkpoint row's NOTE control (reader/SectionNote.tsx + lib/step-notes)
     — the flag and the five verdicts it collapses into. Owner, 2026-08-09:
     "for the flag thing use solar line broken and then go solar duotone when
     selected." So each mark is a PAIR from two Solar styles: "-broken" is the
     rest state (a stroke drawing with a gap in its line, greyed by the button's
     currentColor), "-bold-duotone" the chosen one (two currentColor fills, the
     back one at .5 — it reads as ink where the button's colour is ink). The
     pair is listed longhand, both names, for the same reason step-notes never
     built names from a template: a missing twin must fail THIS script loudly,
     not render nothing. */
  "flag-broken", // the unasked note button
  "lightbulb-broken", // clear
  "lightbulb-bold-duotone",
  "question-circle-broken", // hard to follow
  "question-circle-bold-duotone",
  "clock-circle-broken", // too long
  "clipboard-text-broken", // needs an example
  "danger-triangle-broken", // something looks wrong
];

/* The reader's THIRD Solar surface, and a deliberate one (owner, 2026-08-02).
   Earlier the same day it had three Duotone marks in the checkpoint row — a
   thumbs pair and a bubble — and all three were moved back to MynaUI, because
   Duotone is filled and sat heavy in a row of hairline chrome.

   A callout is the case that rule was drawing a line around, not an exception
   to it: the mark sits alone on a container that gives it its own hue, which is
   exactly where the dashboard tiles put theirs. It is not standing in a line of
   outline icons.

   Solar's surfaces are now: /workspace in Linear, the dashboard stat cards in
   Duotone, and the reader's callout kinds in Duotone. */

const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "components", "icons", "solar.tsx");

const NAMES = [...new Set(ICONS)];

const bodies = {};
for (const name of NAMES) {
  const data = getIconData(solar, name);
  if (!data) throw new Error(`Unknown Solar icon: "${name}"`);
  bodies[name] = iconToSVG(data, { height: 24, width: 24 }).body;
}

const union = NAMES.map((n) => `  | "${n}"`).join("\n");
const entries = NAMES.map((n) => `  "${n}":\n    '${bodies[n].replace(/'/g, "\\'")}',`).join("\n");

writeFileSync(
  OUT,
  `/* AUTO-GENERATED by scripts/gen-solar-icons.mjs — do not edit by hand.
 *
 * Solar Icons (by 480 Design), resolved from the local @iconify-json/solar
 * package at generation time. Add a name to ICONS in the script and rerun
 * \`npm run gen:solar\`.
 *
 * The rest of the app draws MynaUI (see myna.tsx). Solar is scoped to two
 * surfaces: /workspace (Linear, designed against a Solar-drawn reference) and
 * the dashboard's four stat cards (Duotone, the owner's pick).
 */

import type { CSSProperties } from "react";

export type SolarIconName =
${union};

/* Path bodies only — a 24-grid viewBox is added by the component. Linear icons
 * keep stroke="currentColor"; the -bold twins fill with it; -bold-duotone fills
 * with it twice, the back layer at opacity .5. Every style takes the colour of
 * the text around it. */
const BODIES: Record<SolarIconName, string> = {
${entries}
};

/**
 * One icon, inlined as SVG. Safe in server and client components alike: no set
 * is imported at runtime, only the bodies above.
 *
 * \`strokeWidth\` overrides Solar's 1.5 — worth nudging up at small sizes, where
 * a hairline goes faint against a black panel.
 */
export function SolarIcon({
  name,
  size = 20,
  className,
  style,
  strokeWidth,
}: {
  name: SolarIconName;
  size?: number;
  className?: string;
  style?: CSSProperties;
  strokeWidth?: number;
}) {
  const body = strokeWidth
    ? BODIES[name].replace(/stroke-width="[^"]*"/g, \`stroke-width="\${strokeWidth}"\`)
    : BODIES[name];

  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      width={size}
      height={size}
      className={className}
      style={style}
      aria-hidden="true"
      focusable="false"
      dangerouslySetInnerHTML={{ __html: body }}
    />
  );
}
`,
  "utf8",
);

console.log(`Wrote ${NAMES.length} icons to ${OUT}`);
