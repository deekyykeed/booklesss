// Regenerates src/components/icons/plump.tsx from @iconify-json/streamline-plump-color.
//   npm run gen:plump
//
// Streamline **Plump** (free, CC BY 4.0 — attribution owed, same as the other
// Streamline sets in this app). The owner's pick for the 2026-08-27 dashboard:
// "use plump icons from streamline free icons". Plump is already the roundest
// drawing in the app — the course cards' gradient marks and the ask button's
// microphone are both Plump — so the new home screen is the first surface that
// wears it as its whole icon system rather than as one accent.
//
// Same trick as gen-icons.mjs and gen-solar-icons.mjs: the set is 1,000 icons,
// so importing it into a client component would ship the lot. The names below
// are resolved here, at author time, and only their path bodies land in the
// generated module.
//
// ⚠️ TWO COLOURS COME OUT OF THE SET AND BOTH ARE REWRITTEN TO CSS VARIABLES.
// Every Plump Color icon is drawn in exactly two flat values — #8fbffa for the
// light layer and #2859c5 for the dark — plus #ffffff for the paper inside a
// shape. `currentColor` would be wrong here (it would flatten the two layers
// into one silhouette and the drawing would disappear), so the bodies are
// emitted with `var(--plump-light)` and `var(--plump-dark)` in their place and
// the component sets that pair. That is what gives the nav a real off/on
// grammar out of ONE set rather than two packages that have to agree on names
// — the lesson `ultimate.tsx` and `freehand.tsx` both paid for (WORKSPACE.md).
//
// The white stays white. It is the paper inside a mark, and every surface that
// draws these is white or #f9f9f7.
import { getIconData, iconToSVG } from "@iconify/utils";
import plump from "@iconify-json/streamline-plump-color/icons.json" with { type: "json" };
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ICONS = [
  // The home dock's four small marks, left to right around the big button.
  "home-1", // Home
  "graduation-cap", // Courses
  "bookmark", // Saved
  "cog", // You / settings
  // The sessions list.
  "button-play-circle", // "Listen" on a session card
  "voice-scan-1", // the empty state, when a student has no sessions yet
];

const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "components", "icons", "plump.tsx");

const NAMES = [...new Set(ICONS)];

const bodies = {};
for (const name of NAMES) {
  const data = getIconData(plump, name);
  if (!data) throw new Error(`Unknown Streamline Plump icon: "${name}"`);
  const { body } = iconToSVG(data, { height: 48, width: 48 });
  const painted = body
    .replaceAll("#8fbffa", "var(--plump-light)")
    .replaceAll("#2859c5", "var(--plump-dark)");
  // A body that came back without either colour is a name that resolved to a
  // drawing this component cannot tint — better to fail the generator than to
  // ship a mark that ignores its own state.
  if (painted === body) throw new Error(`"${name}" carries neither Plump colour — wrong set?`);
  bodies[name] = painted;
}

const union = NAMES.map((n) => `  | "${n}"`).join("\n");
const entries = NAMES.map((n) => `  "${n}":\n    '${bodies[n].replace(/'/g, "\\'")}',`).join("\n");

writeFileSync(
  OUT,
  `/* AUTO-GENERATED by scripts/gen-plump-icons.mjs — do not edit by hand.
 *
 * Streamline Plump (free, CC BY 4.0), resolved from the local
 * @iconify-json/streamline-plump-color package at generation time. Add a name
 * to ICONS in the script and rerun 'npm run gen:plump'.
 *
 * THE TWO LAYERS ARE CSS VARIABLES, not currentColor — see the script's header
 * for why. A caller sets '--plump-light' and '--plump-dark'; the defaults below
 * are the app's muted grey, which is the resting state of every mark in the
 * home dock.
 */

import type { CSSProperties } from "react";

export type PlumpIconName =
${union};

/* Path bodies only — the 48-grid viewBox is added by the component. Plump is
 * drawn on 48 and is NOT rescaled to 24 here: its strokes are 3 units wide and
 * re-gridding them is what makes a plump mark look like a thin one. */
const BODIES: Record<PlumpIconName, string> = {
${entries}
};

/**
 * One Plump mark, inlined as SVG. Safe in server and client components alike:
 * no set is imported at runtime, only the bodies above.
 *
 * Pass 'light' and 'dark' to colour it — a pair, always, because the drawing
 * is two layers and setting one leaves the other at its default. The home dock
 * passes the app's muted grey at rest and the accent when a row is current.
 */
export function PlumpIcon({
  name,
  size = 24,
  light,
  dark,
  className,
  style,
}: {
  name: PlumpIconName;
  size?: number;
  light?: string;
  dark?: string;
  className?: string;
  style?: CSSProperties;
}) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 48 48"
      width={size}
      height={size}
      className={className}
      style={
        {
          "--plump-light": light ?? "var(--color-placeholder)",
          "--plump-dark": dark ?? "var(--color-muted)",
          ...style,
        } as CSSProperties
      }
      aria-hidden="true"
      focusable="false"
      dangerouslySetInnerHTML={{ __html: BODIES[name] }}
    />
  );
}
`,
  "utf8",
);

console.log("Wrote " + NAMES.length + " icons to " + OUT);
